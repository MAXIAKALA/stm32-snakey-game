/**
 *获取位图
 *@param BMP_ID id 位图id,使用对应宏获取
 *@return void
 */
BMP* getBmpById(BMP_ID id)
{	
	switch(id)
	{
		case OPEN_BMP:
			_bmp.height = 32;
			_bmp.width = 32;		
			_bmp.bmp = (unsigned char*)openIcon;		
		break;
		
		case CLOSE_BMP:
			_bmp.height = 32;
			_bmp.width = 32;		
			_bmp.bmp = (unsigned char*)closeIcon;		
		break;
			
		case ADJUST_BMP:
			_bmp.height = 32;
			_bmp.width = 32;		
			_bmp.bmp = (unsigned char*)adjustIcon;		
		break;

		default:return NULL;
	}
	
	return &_bmp;
}
